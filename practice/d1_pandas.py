"""
Day 2 练习 3：pandas 速成（由教练讲解，不需要看文档）
文件：D:\\Software\\llm-eval-practice\\d1_pandas.py

【一句话理解 pandas】
    它就是一个"能用代码操作的 Excel 表格"。
    你过去在 Excel 里做的：筛选、排序、透视表、算比例 —— pandas 都能做，
    区别是它能对几万条评测结果一键批量算，而且能写进脚本自动跑。

【为什么评测岗必须有它】
    模型跑完 500 道题，你要交的不是 500 行原始结果，而是：
        DeepSeek 通过率 83.3%，Qwen 通过率 50%，其中 Qwen 在"折旧"类只有 33.3%
    这句话就是用 groupby + mean 算出来的。

【只学这 6 个操作就够】
    ① pd.read_csv()      读进来
    ② df.head() / .shape 看一眼长什么样
    ③ df[df["列"] == 值]  筛选
    ④ df.groupby("列")[...].mean()   算通过率 ★核心★
    ⑤ df.groupby([...])[...].agg()   一张多维报表
    ⑥ df.to_csv()        写出去

运行方式（务必先进入项目文件夹，否则文件会生成到别处）：
    cd /d D:\\Software\\llm-eval-practice
    venv\\Scripts\\python.exe d1_pandas.py
"""

import pandas as pd

# ============================================================
# 第 0 步：先造一份"评测结果"数据
# ------------------------------------------------------------
# 这不是学习重点，只是为了让你有东西可练。
# 它模拟的是：你未来的 eval_batch.py 批量调完模型后得到的原始结果。
# 格式：一行 = 一道题的结果
# ============================================================
rows = [
    # (题号, 题目分类, 被测模型, 是否答对)
    (1,  "折旧", "deepseek", True),
    (2,  "折旧", "deepseek", True),
    (3,  "折旧", "deepseek", False),
    (4,  "报表", "deepseek", True),
    (5,  "报表", "deepseek", True),
    (6,  "报表", "deepseek", True),
    (7,  "折旧", "qwen", True),
    (8,  "折旧", "qwen", False),
    (9,  "折旧", "qwen", True),
    (10, "报表", "qwen", False),
    (11, "报表", "qwen", False),
    (12, "报表", "qwen", True),
]

df_raw = pd.DataFrame(rows, columns=["id", "category", "model", "judge"])
df_raw.to_csv("eval_results.csv", index=False, encoding="utf-8-sig")
print("=" * 60)
print("原始评测结果已生成：eval_results.csv（12 行）")
print("=" * 60)

# ============================================================
# ① read_csv —— 读进来，得到一个 DataFrame（就是那张表格）
# ============================================================
df = pd.read_csv("eval_results.csv")

print("\n【1】读进来了，它长这样：")
print("   形状(行, 列)：", df.shape)
print("   列名：", list(df.columns))

# ============================================================
# ② head() —— 只看前几行，避免刷屏
# ============================================================
print("\n【2】前 3 行长什么样（head 就是「看几眼」）：")
print(df.head(3))

# ============================================================
# ③ 筛选 —— 用条件挑出想要的行
# ------------------------------------------------------------
# 记住这个写法：df[ df["列名"] == "值" ]
# 外层 df[...] 是"挑行"，内层是"条件"
# ============================================================
print("\n【3】只看 deepseek 的结果：")
print(df[df["model"] == "deepseek"])

print("\n【3-2】只看答错的题（False）：")
print(df[df["judge"] == False])

# ============================================================
# ④ groupby + mean —— ★本课核心★ 算通过率
# ------------------------------------------------------------
# 拆开读：
#   groupby("model")      → 按模型分组（等于 Excel 的分类汇总）
#   ["judge"]             → 只关心"是否答对"这一列
#   .mean()               → 求平均
# True 算 1、False 算 0，平均值 = 答对的比例 = 通过率
# ============================================================
print("\n【4】★每个模型的通过率★（这一行就是评测报告的核心）：")
print(df.groupby("model")["judge"].mean().round(3))

# ============================================================
# ⑤ 多维分组 + agg —— 一张像样的报表
# ------------------------------------------------------------
# groupby 传列表 = 按两个维度分组（模型 × 分类）
# agg(["count","sum","mean"]) = 一次算出三个指标
#   count=题数  sum=答对题数  mean=通过率
# ============================================================
print("\n【5】模型 × 分类 的详细报表：")
report = (
    df.groupby(["model", "category"])["judge"]
    .agg(["count", "sum", "mean"])
    .round(3)
)
report.columns = ["题数", "答对数", "通过率"]
print(report)

# ============================================================
# ⑥ to_csv —— 写出去（评测报告的收尾动作）
# ------------------------------------------------------------
# index=False：不要把 pandas 的行号当成一列写进去
# encoding="utf-8-sig"：保证 Excel 双击打开不乱码
# ============================================================
report.to_csv("eval_report.csv", encoding="utf-8-sig")
print("\n【6】报表已导出：eval_report.csv（用 Excel 双击打开看看）")

