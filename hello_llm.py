import os
from openai import OpenAI

# ============================================================
# 第 1 步：拿到 API key（从环境变量读，绝不能写死在代码里）
# ------------------------------------------------------------
# 为什么不写在代码里？因为代码要传到 GitHub。
# 一旦 key 进了公开仓库，几分钟内就会被爬虫扫走盗刷。
# 这是评测/研发岗面试会问的合规题，标准答案就是"环境变量管理密钥"。
# ============================================================
api_key = os.environ.get("DEEPSEEK_API_KEY")
if not api_key:
    raise SystemExit(
        "没找到环境变量 DEEPSEEK_API_KEY。\n"
        "请确认已把它加到系统环境变量，并且重启过终端（旧终端读不到新变量）。"
    )

# ============================================================
# 第 2 步：创建"客户端"（相当于拿到快递公司的寄件通道）
# ------------------------------------------------------------
# DeepSeek 兼容 OpenAI 的接口协议，所以可以直接用 openai 这个官方库，
# 只需要把 base_url 换成 DeepSeek 的地址。
# 好处：以后换成通义、智谱、Kimi，代码几乎不用改，只改 base_url 和 model。
# ============================================================
client = OpenAI(api_key=api_key, base_url="https://api.deepseek.com")

# ============================================================
# 第 3 步：发请求（这是整个脚本的核心）
# ============================================================
response = client.chat.completions.create(
    model="deepseek-chat",

    # messages 是一个"对话列表"，里面的三种角色必须分清楚：
    #   system    —— 设定身份和规则（AI 的"岗位说明书"，用户看不见）
    #   user      —— 用户这一轮说的话（就是你要它回答的问题）
    #   assistant —— 模型之前的回答（多轮对话时才用，现在用不到）
    messages=[
        {
            "role": "system",
            "content": "你是一个财务行业的初学者，回答啰嗦。",
        },
        {
            "role": "user",
            "content": "资产折旧常用的会计处理方法有哪些？",
        },
    ],

    # temperature=0：每次取概率最高的答案，尽量可复现。
    # 评测时固定成 0，是为了"同样的题跑出来的结果能对比"。
    temperature=0,
)

# ============================================================
# 第 4 步：把回答取出来
# ------------------------------------------------------------
# 返回的是一个结构体，不是纯文本，所以要用路径一层层取：
#   response.choices[0]        取第 1 个候选回答（默认只返回 1 个）
#   .message.content           取里面的文字内容
# 这个"从 JSON 里一层层取字段"的动作，和你过去用 postman 看响应
# 返回体其实是同一件事 —— 你已经很熟了。
# ============================================================
answer = response.choices[0].message.content
print("模型回答：", answer)

# ============================================================
# 第 5 步：打印用量（这是评测/成本分析的源头数据）
# ------------------------------------------------------------
# usage 里三个数字你以后会天天看：
#   prompt_tokens      输入消耗（你发过去的字数）
#   completion_tokens  输出消耗（模型答的字数）
#   total_tokens       合计 —— 计费的依据
# 后面做"每次调用成本"和"性能压测"时，就是统计这几个值。
# ============================================================
u = response.usage
print(f"[用量] 输入 {u.prompt_tokens} + 输出 {u.completion_tokens} = {u.total_tokens} tokens")

